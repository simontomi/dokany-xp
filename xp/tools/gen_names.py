"""Generates sys/xp_ioctl.h: the IOCTL/FSCTL codes the driver names in its log
table (util/ioctl.inc) that the WDK 7.1 XP headers do not define. Values come
from the WDK 7.1 headers (any NTDDI section) or the Windows 10 SDK.

Usage (from the repository root, after a failed driver build):
  python xp/tools/gen_names.py xp/sys/buildfre_wxp_x86.err
"""
import glob
import re
import sys

BOMS = (b"\xff\xfe", b"\xfe\xff")


def read_text(path):
    raw = open(path, "rb").read()
    if raw[:2] in BOMS:
        return raw.decode("utf-16")
    return raw.decode("latin-1")


heads = (glob.glob(r"C:\WinDDK\7600.16385.1\inc\ddk\*.h") +
         glob.glob(r"C:\WinDDK\7600.16385.1\inc\api\*.h") +
         glob.glob(r"C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0\shared\*.h") +
         glob.glob(r"C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0\um\*.h"))
defs = {}
for f in heads:
    t = re.sub(r"\\\r?\n", " ", read_text(f))
    for m in re.finditer(
            r"^[ \t]*#define[ \t]+((?:IOCTL|FSCTL)_[A-Z0-9_]+)[ \t]+(.+?)[ \t]*(?://.*|/\*.*)?$",
            t, re.M):
        defs.setdefault(m.group(1), m.group(2).strip())

undeclared = set()
for line in open(sys.argv[1], encoding="mbcs", errors="replace"):
    m = re.search(r"'((?:IOCTL|FSCTL)_[A-Z0-9_]+)' : undeclared identifier", line)
    if m:
        undeclared.add(m.group(1))

try:
    known = open("sys/xp_ioctl.h", encoding="utf-8").read()
except IOError:
    known = ""
have = dict(re.findall(r"#define ((?:IOCTL|FSCTL)_[A-Z0-9_]+) (.+)", known))
for n in sorted(undeclared):
    if n in defs:
        have[n] = defs[n]
    else:
        print("NOT FOUND", n)

out = ["// IOCTL and FSCTL codes the driver only names in its log table",
       "// (util/ioctl.inc) and the WDK 7.1 XP headers lack. Generated by",
       "// xp/tools/gen_names.py from the WDK 7.1 and Windows 10 SDK headers.",
       "#ifndef DOKAN_XP_IOCTL_H_", "#define DOKAN_XP_IOCTL_H_", ""]
for n in sorted(have):
    out += ["#ifndef %s" % n, "#define %s %s" % (n, have[n]), "#endif"]
out += ["", "#endif // DOKAN_XP_IOCTL_H_", ""]
open("sys/xp_ioctl.h", "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("defined", len(have))
